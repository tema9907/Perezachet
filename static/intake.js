$("generateBtn").addEventListener("click", async () => {
  const studentName = $("fName").value.trim();
  if (!studentName) { toast("Введите ФИО студента", "error"); $("fName").focus(); return; }

  const subjects = [];
  for (const [, s] of subjectsMap) {
    const name = (s.name || "").trim();
    if (!name) continue;
    const certs = [];
    for (const [, c] of s.certsMap) certs.push({ source: c.source || "" });
    subjects.push({ name, certs });
  }
  if (subjects.length === 0) { toast("Добавьте хотя бы один предмет", "error"); return; }

  const payload = {
    student_name: studentName,
    faculty: cbFaculty.getValue(),
    department: cbDepartment.getValue(),
    group: cbGroup.getValue(),
    course_year: cbCourse.getValue(),
    phone: $("fPhone").value.trim(),
    subjects,
  };

  const formData = new FormData();
  formData.append("data", JSON.stringify(payload));

  let si = 0;
  for (const [, s] of subjectsMap) {
    if (!(s.name || "").trim()) continue;
    let ci = 0;
    for (const [, c] of s.certsMap) {
      if (c.file) formData.append(`cert_${si}_${ci}`, c.file, c.file.name);
      ci++;
    }
    si++;
  }

  $("generateBtn").disabled = true;
  $("generateBtn").textContent = "Формируем...";
  $("resultBlock").classList.add("hidden");

  try {
    const res = await fetch("/api/intake/generate", { method: "POST", body: formData });
    if (!res.ok) { const errText = await res.text().catch(() => res.statusText); throw new Error(errText); }
    const blob = await res.blob();
    const dispo = res.headers.get("Content-Disposition") || "";
    const m = dispo.match(/filename\*?=(?:UTF-8''|utf-8''|)"?([^";]+)"?/i);
    let docxName = "Заявление.docx";
    if (m) { try { docxName = decodeURIComponent(m[1]); } catch { docxName = m[1]; } }
    const dlUrl = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = dlUrl; a.download = docxName;
    document.body.appendChild(a); a.click(); a.remove();
    URL.revokeObjectURL(dlUrl);

    const driveUrl = res.headers.get("X-Drive-Url") || "";
    const driveErrRaw = res.headers.get("X-Drive-Error") || "";
    const driveErr = driveErrRaw ? decodeURIComponent(driveErrRaw) : "";
    $("resultBlock").classList.remove("hidden");
    $("resultText").textContent = `Документ «${docxName}» скачан. PDF с сертификатами:`;
    if (driveUrl) {
      $("driveLink").href = driveUrl; $("driveLink").classList.remove("hidden");
      $("driveErrorText").classList.add("hidden");
      toast("Документы сформированы и отправлены на Google Drive", "success");
    } else {
      $("driveLink").classList.add("hidden");
      $("driveErrorText").textContent = driveErr ? "Drive: " + driveErr : "Drive не настроен — PDF не отправлен";
      $("driveErrorText").classList.remove("hidden");
      toast(driveErr ? "DOCX скачан, Drive недоступен" : "DOCX скачан (Drive не настроен)", driveErr ? "error" : "");
    }
  } catch (e) {
    toast("Ошибка: " + e.message, "error");
  } finally {
    $("generateBtn").disabled = false;
    $("generateBtn").textContent = "Сформировать документы";
  }
});

function escapeAttr(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;").replace(/</g, "&lt;")
    .replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}
