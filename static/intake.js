// ==== Subject management ====
// subjectsMap: id -> { name, certsMap: Map(certId -> { source, file, fileName }) }
let nextSubjectId = 0;
let nextCertId = 0;
const subjectsMap = new Map();

function updateSubjectNumbers() {
  let n = 1;
  document.querySelectorAll(".subject-row").forEach((row) => {
    row.querySelector(".subject-num").textContent = n++;
  });
}

function addCertItem(subjectId, certsContainer) {
  const certId = nextCertId++;
  const entry = subjectsMap.get(subjectId);
  entry.certsMap.set(certId, { source: "", file: null, fileName: "" });

  const item = document.createElement("div");
  item.className = "cert-item";
  item.dataset.certId = certId;
  item.innerHTML = `
    <input type="text" class="cert-source-input" placeholder="Откуда (Coursera, Udemy, Stepik...)">
    <label class="cert-upload-label">
      <input type="file" accept="application/pdf,image/jpeg,image/png,image/webp,image/gif" class="cert-file-input" hidden>
      <span class="cert-upload-btn btn-ghost">Прикрепить PDF</span>
    </label>
    <span class="cert-name-label"></span>
    <button class="btn-danger-ghost cert-remove-btn" title="Удалить сертификат">✕</button>
  `;

  const sourceInput = item.querySelector(".cert-source-input");
  sourceInput.addEventListener("input", () => {
    entry.certsMap.get(certId).source = sourceInput.value.trim();
  });

  const fileInput = item.querySelector(".cert-file-input");
  const certNameLabel = item.querySelector(".cert-name-label");
  fileInput.addEventListener("change", () => {
    const f = fileInput.files[0];
    if (!f) return;
    const _ext = f.name.split(".").pop().toLowerCase(); if (!["pdf","jpg","jpeg","png","webp","gif"].includes(_ext)) {
      toast("Нужен .pdf файл", "error"); fileInput.value = ""; return;
    }
    const c = entry.certsMap.get(certId);
    c.file = f; c.fileName = f.name;
    certNameLabel.textContent = f.name;
    item.querySelector(".cert-upload-btn").textContent = "Заменить файл";
    // Show image thumbnail for images
    const _ext2 = f.name.split(".").pop().toLowerCase();
    let prevImg = item.querySelector(".cert-image-preview");
    if (prevImg) prevImg.remove();
    if (["jpg","jpeg","png","webp","gif"].includes(_ext2)) {
      const img = document.createElement("img");
      img.className = "cert-image-preview";
      img.src = URL.createObjectURL(f);
      certNameLabel.before(img);
    }
  });

  item.querySelector(".cert-remove-btn").addEventListener("click", () => {
    entry.certsMap.delete(certId);
    item.remove();
  });

  certsContainer.appendChild(item);
}

function addSubjectRow(initialName = "") {
  const id = nextSubjectId++;
  subjectsMap.set(id, { name: initialName, certsMap: new Map() });

  const row = document.createElement("div");
  row.className = "subject-row";
  row.dataset.subjectId = id;
  row.innerHTML = `
    <span class="subject-num"></span>
    <div class="subject-content">
      <div class="subject-name-row">
        <div class="combobox" style="flex:1;min-width:0;">
          <input class="cb-input" type="text" placeholder="Название дисциплины..."
                 value="${escapeAttr(initialName)}" autocomplete="off">
          <div class="cb-dropdown hidden"></div>
        </div>
        <button class="btn-danger-ghost subject-remove-btn" title="Удалить предмет">✕</button>
      </div>
      <div class="subject-certs-container"></div>
      <button class="btn-ghost add-cert-btn">+ Добавить сертификат</button>
    </div>
  `;

  const cb = initCombobox(
    row.querySelector(".combobox"),
    () => SUBJECTS,
    (val) => { subjectsMap.get(id).name = val; }
  );
  if (initialName) cb.setValue(initialName);

  const certsContainer = row.querySelector(".subject-certs-container");

  row.querySelector(".add-cert-btn").addEventListener("click", () => {
    addCertItem(id, certsContainer);
  });

  row.querySelector(".subject-remove-btn").addEventListener("click", () => {
    subjectsMap.delete(id);
    row.remove();
    updateSubjectNumbers();
  });

  $("subjectList").appendChild(row);
  updateSubjectNumbers();
  addCertItem(id, certsContainer); // первый сертификат автоматически
}

